// One-off dev tool: traces the white castle-shield from the brand logo into an SVG path.
// Usage: node tools/vectorize-logo.cjs
const potrace = require('potrace');
const fs = require('fs');
const path = require('path');

const input = path.join(__dirname, '..', 'public', 'brand', 'logo.jpg');
const output = path.join(__dirname, '..', 'src', 'app', 'core', 'logo-shield.path.ts');

const trace = new potrace.Potrace({
  threshold: 215, // keep only the (near-)white parts of the logo
  blackOnWhite: false, // trace the LIGHT pixels
  turdSize: 40,
  optTolerance: 0.6,
  alphaMax: 1,
});

trace.loadImage(input, (err) => {
  if (err) throw err;
  const svg = trace.getSVG();
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1];
  fs.writeFileSync(
    output,
    `/** Auto-generated by tools/vectorize-logo.cjs from public/brand/logo.jpg. */\n` +
      `export const LOGO_SHIELD_VIEWBOX = '${viewBox}';\n` +
      `export const LOGO_SHIELD_PATH =\n  '${d}';\n`,
  );
  console.log('viewBox', viewBox, 'path length', d.length);
});
